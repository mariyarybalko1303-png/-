# Пакет Flux.jl є стандартом для машинного навчання у Julia
using Flux
using Flux: train!
using Random

# ====================================================================
# 1. Генерація синтетичних даних для класифікації
# ====================================================================
# Створимо задачу класифікації точок на площині (2 ознаки) на 3 класи.
Random.seed!(1234)

n_samples = 300
X = rand(Float32, 2, n_samples) # Матриця розміром 2 x 300 (по 2 ознаки для 300 точок)

# Визначимо класи на основі простих геометричних правил
y_raw = Int[]
for i in 1:n_samples
    x1, x2 = X[1, i], X[2, i]
    if x1 + x2 < 0.8
        push!(y_raw, 1)      # Клас 1: точки поблизу початку координат
    elseif x1 - x2 > 0.0
        push!(y_raw, 2)      # Клас 2: нижня права частина площини
    else
        push!(y_raw, 3)      # Клас 3: верхня ліва частина площини
    end
end

# Перетворюємо мітки класів (1, 2, 3) у One-Hot представлення (матриця 3 x 300)
y = Flux.onehotbatch(y_raw, 1:3)

# ====================================================================
# 2. Опис архітектури нейромережі (Multi-Layer Perceptron)
# ====================================================================
# Шар 1 (Вхідний): 2 ознаки -> 10 нейронів (функція активації ReLU)
# Шар 2 (Прихований): 10 нейронів -> 3 нейрони (вихідні класи)
# Функція активації Softmax перетворює вихідні значення у розподіл ймовірностей
model = Chain(
    Dense(2 => 10, relu),
    Dense(10 => 3),
    softmax
)

# ====================================================================
# 3. Налаштування навчання (Функція втрат та Оптимізатор)
# ====================================================================
# Використовуємо перехресну ентропію (Cross Entropy) для класифікації
loss(model, x, y) = Flux.crossentropy(model(x), y)

# Оптимізатор Adam з кроком навчання (learning rate) 0.01
# У нових версіях Flux (v0.13+) ми створюємо стан оптимізатора за допомогою Flux.setup
opt_state = Flux.setup(Flux.Adam(0.01), model)

# ====================================================================
# 4. Процес навчання (Training Loop)
# ====================================================================
epochs = 200
data = [(X, y)] # Навчальний набір у вигляді масиву кортежів (features, labels)

println("=== Початок навчання нейромережі з Flux.jl ===")

for epoch in 1:epochs
    # Функція train! оновлює ваги моделі на основі градієнтів функції втрат
    Flux.train!(loss, model, data, opt_state)
    
    # Виводимо проміжні результати кожні 50 епох
    if epoch % 50 == 0 || epoch == 1
        current_loss = loss(model, X, y)
        println("Епоха $epoch: Помилка (Loss) = $(round(current_loss, digits=4))")
    end
end

# ====================================================================
# 5. Оцінка моделі та тестування
# ====================================================================
# Отримуємо передбачення для всієї вибірки
predictions = model(X)

# Перетворюємо One-Hot розподіл назад у конкретні номери класів (1, 2, 3)
predicted_classes = Flux.onecold(predictions, 1:3)

# Обчислюємо точність (Accuracy)
accuracy = sum(predicted_classes .== y_raw) / length(y_raw)
println("\n=== Результати навчання ===")
println("Точність (Accuracy) моделі на тренувальних даних: $(round(accuracy * 100, digits=2))%")

# Протестуємо нейромережу на новій точці
new_point = Float32[0.2, 0.3] # Очікуваний клас: 1 (оскільки 0.2 + 0.3 = 0.5 < 0.8)
model_prediction = model(new_point)
predicted_class = Flux.onecold(model_prediction, 1:3)

println("\n=== Перевірка на нових даних ===")
println("Вхідні дані (координати точки): $new_point")
println("Розподіл ймовірностей класів: ", round.(model_prediction, digits=4))
println("Передбачений клас: $predicted_class (Очікувався: 1)")
